  var track = document.getElementById('track');
  var slides = track ? track.children : [];
  var dots = document.getElementById('dots');
  var currentSlide = 0;
  var language = 'pt';

  function go(index) {
    index = Math.max(0, Math.min(slides.length - 1, index));
    if (!slides[index]) return;
    track.scrollTo({
      left: slides[index].offsetLeft - track.offsetLeft,
      behavior: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth'
    });
  }

  function mark() {
    if (!track || !slides.length || !dots) return;
    var width = slides[0].getBoundingClientRect().width + 20;
    currentSlide = Math.round(track.scrollLeft / width);
    for (var i = 0; i < dots.children.length; i++) {
      dots.children[i].setAttribute('aria-current', i === currentSlide ? 'true' : 'false');
    }
  }

  if (track && dots) {
    for (var i = 0; i < slides.length; i++) {
      (function (index) {
        var button = document.createElement('button');
        button.type = 'button';
        button.setAttribute('role', 'tab');
        button.onclick = function () { go(index); };
        dots.appendChild(button);
      })(i);
    }

    track.addEventListener('scroll', function () { window.requestAnimationFrame(mark); });
    track.addEventListener('keydown', function (event) {
      if (event.key === 'ArrowRight') { event.preventDefault(); go(currentSlide + 1); }
      if (event.key === 'ArrowLeft') { event.preventDefault(); go(currentSlide - 1); }
    });

    document.getElementById('prev').onclick = function () { go(currentSlide - 1); };
    document.getElementById('next').onclick = function () { go(currentSlide + 1); };
  }

  function setText(selector, value) {
    var element = document.querySelector(selector);
    if (element) element.textContent = value;
  }

